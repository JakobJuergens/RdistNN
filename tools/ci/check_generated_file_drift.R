#!/usr/bin/env Rscript
# Regenerate in an isolated source tree; the checkout is never modified.
.read_raw_file <- function(path) {
  if (!file.exists(path)) return(NULL)
  readBin(path, "raw", n = file.info(path)$size)
}

.copy_source_input <- function(path, destination) {
  if (!file.exists(path)) return(invisible(NULL))
  files <- if (dir.exists(path)) list.files(path, recursive = TRUE,
    all.files = TRUE, full.names = TRUE, no.. = TRUE) else path
  files <- files[!dir.exists(files) & !grepl("[.](o|obj|so|dll|dylib)$|/symbols[.]rds$", files)]
  for (file in files) {
    target <- file.path(destination, file)
    dir.create(dirname(target), recursive = TRUE, showWarnings = FALSE)
    if (!file.copy(file, target, overwrite = TRUE)) stop("Cannot copy ", file, call. = FALSE)
  }
}

main <- function(args = commandArgs(TRUE)) {
  if (length(args) && !(length(args) == 2L && args[1L] == "--package")) {
    stop("Usage: Rscript check_generated_file_drift.R [--package PATH]", call. = FALSE)
  }
  root <- normalizePath(if (length(args)) args[2L] else ".", mustWork = TRUE)
  old <- setwd(root)
  on.exit(setwd(old), add = TRUE)
  for (pkg in c("roxygen2", "Rcpp")) {
    if (!requireNamespace(pkg, quietly = TRUE)) stop("Package '", pkg, "' is required.", call. = FALSE)
  }
  version <- read.dcf("DESCRIPTION")[1L, ]
  declared <- version["Config/roxygen2/version"]
  if (!is.na(declared) && declared != as.character(utils::packageVersion("roxygen2"))) {
    stop("Use the declared roxygen2 version ", declared, " to check generated files.", call. = FALSE)
  }
  temporary <- tempfile("generated-drift-")
  dir.create(temporary)
  on.exit(unlink(temporary, recursive = TRUE, force = TRUE), add = TRUE)
  for (path in c("DESCRIPTION", "NAMESPACE", "R", "src", "man")) {
    .copy_source_input(path, temporary)
  }
  # Start generated topics from source, so removed/orphan topics cannot survive
  # merely because they were copied into the regeneration tree.
  for (path in list.files(file.path(temporary, "man"), "[.]Rd$", full.names = TRUE)) {
    if (any(grepl("Generated by roxygen2", readLines(path, warn = FALSE), fixed = TRUE))) unlink(path)
  }
  roxygen2::roxygenise(temporary, roclets = c("namespace", "rd"), load = "source")
  native <- length(list.files(file.path(temporary, "src"), "[.]cpp$", recursive = TRUE)) > 0L
  if (native) Rcpp::compileAttributes(pkgdir = temporary, verbose = FALSE)
  rd <- union(list.files("man", "[.]Rd$"),
              list.files(file.path(temporary, "man"), "[.]Rd$"))
  targets <- c("NAMESPACE", if (native) c("R/RcppExports.R", "src/RcppExports.cpp"),
               file.path("man", rd))
  drift <- targets[!vapply(targets, function(path) {
    identical(.read_raw_file(path), .read_raw_file(file.path(temporary, path)))
  }, logical(1))]
  if (length(drift)) {
    stop(paste0("Generated-file drift detected:\n", paste0("- ", drift, collapse = "\n"),
      "\nRegenerate with devtools::document() and Rcpp::compileAttributes()."), call. = FALSE)
  }
  cat(sprintf("No generated-file drift detected: namespace, %d Rd topics%s.\n",
              length(rd), if (native) ", Rcpp exports" else ""))
}

main()
