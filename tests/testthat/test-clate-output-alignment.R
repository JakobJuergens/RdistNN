test_that("ratio summaries expose the existing coefficient-table schema", {
  fit <- .ratio_fixture()
  out <- summary(fit)
  expect_s3_class(out, "summary.affine_ratio_result")
  expect_type(out, "list")
  expect_true(all(c("coefficients", "level", "has_se", "meta", "components", "status") %in% names(out)))
  tab <- out$coefficients
  expect_named(tab, c("estimate", "std.error", "statistic", "p.value", "conf.low", "conf.high"))
  expect_identical(rownames(tab), "target_1")
  expect_equal(tab$estimate, 4)
  expect_equal(tab$std.error, sqrt(34))
  expect_equal(tab$statistic, 4 / sqrt(34))
  expect_equal(tab$p.value, 2 * stats::pnorm(-4 / sqrt(34)))
  expect_equal(as.numeric(tab[1L, c("conf.low", "conf.high")]), as.numeric(confint(fit)))
  expect_true(out$has_se)
  expect_equal(out$level, .95)
  expect_identical(out$meta, fit$meta)
  expect_equal(out$components$numerator, 2)
  expect_equal(out$components$denominator, .5)
  expect_equal(out$status, fit$status)
  expect_output(ret <- withVisible(print(out)), "estimate")
  expect_false(ret$visible)
  expect_identical(ret$value, out)
})

test_that("aligned summary tables retain unavailable target rows", {
  .with_partial_result_warning({
  .with_distance_tie_warning({
  fit <- .ratio_fixture(X0 = matrix(c(0, 3, 5), ncol = 1L), x0 = NULL,
                        denominator = c(0, 0, -1, 2), s = 3L)
  out <- summary(fit)
  expect_identical(rownames(out$coefficients), paste0("target_", 1:3))
  expect_true(is.na(out$coefficients$estimate[1L]))
  expect_true(all(is.na(out$coefficients[1L, ])))
  expect_true(all(is.finite(out$coefficients$estimate[-1L])))
  expect_equal(out$status$ratio_status, c("zero_denominator", "ok", "ok"))
  point <- summary(.ratio_fixture(se = FALSE))
  expect_false(point$has_se)
  expect_equal(point$coefficients$estimate, 4)
  expect_true(all(is.na(point$coefficients[1L, -1L])))
  zero <- summary(.ratio_fixture(numerator = 4 * c(1, -1, 2, 1)))
  expect_equal(zero$coefficients$std.error, 0)
  expect_true(all(is.na(zero$coefficients[1L, c("statistic", "p.value", "conf.low", "conf.high")])))
  })
  })
})

test_that("CLATE estimates use the common tidy extraction schema", {
  fit <- .ratio_fixture(X0 = matrix(c(0, 5), ncol = 1L), x0 = NULL)
  tab <- plot_data_estimates(fit)
  expect_named(tab, c("target_id", "coef", "estimate", "se", "ci_lower", "ci_upper", "x0_1"))
  expect_equal(tab$target_id, 1:2)
  expect_identical(tab$coef, rep("theta", 2L))
  expect_equal(tab$estimate, fit$theta)
  expect_equal(tab$se, fit$se)
  expect_equal(tab$ci_lower, as.numeric(confint(fit)[, 1L]))
  expect_equal(tab$ci_upper, as.numeric(confint(fit)[, 2L]))
  expect_equal(tab$x0_1, c(0, 5))
})
